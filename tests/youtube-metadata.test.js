'use strict';

const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const {
    parseCleanTrackAndArtist,
    parseProvidedToYouTubeDescription,
    parseGeneralDescriptionAlbumHints,
    extractYouTubeWatchPageMetadata,
    mergeResolvedTrackMetadata,
    cleanCaptionTextToLyrics,
    inferSuggestedSongLanguage,
    isGenericUploaderChannel
} = require('../lib/youtube-metadata');

describe('YouTube & YT Music metadata parser + subtitle cleaner', () => {
    it('limpia títulos de YouTube M/V, YT Music Topic y colaboraciones', () => {
        const drip = parseCleanTrackAndArtist("BABYMONSTER - 'DRIP' M/V", 'BABYMONSTER');
        assert.strictEqual(drip.title, 'DRIP');
        assert.strictEqual(drip.mainArtist, 'BABYMONSTER');
        assert.deepStrictEqual(drip.collaborators, []);

        const apt = parseCleanTrackAndArtist('ROSÉ & Bruno Mars - APT. (Official Music Video)', 'ROSÉ');
        assert.strictEqual(apt.title, 'APT.');
        assert.strictEqual(apt.mainArtist, 'ROSÉ');
        assert.deepStrictEqual(apt.collaborators, ['Bruno Mars']);

        const topicTrack = parseCleanTrackAndArtist('Forever', 'BABYMONSTER - Topic');
        assert.strictEqual(topicTrack.title, 'Forever');
        assert.strictEqual(topicTrack.mainArtist, 'BABYMONSTER');
    });

    it('extrae álbum, año y tipo desde descripción oficial "Provided to YouTube by"', () => {
        const desc = [
            'Provided to YouTube by YG PLUS',
            '',
            'DRIP · BABYMONSTER',
            '',
            'DRIP',
            '',
            '℗ YG Entertainment',
            '',
            'Released on: 2024-11-01',
            '',
            'Auto-generated by YouTube.'
        ].join('\n');

        const parsed = parseProvidedToYouTubeDescription(desc);
        assert.ok(parsed);
        assert.strictEqual(parsed.title, 'DRIP');
        assert.strictEqual(parsed.mainArtist, 'BABYMONSTER');
        assert.strictEqual(parsed.albumTitle, 'DRIP');
        assert.strictEqual(parsed.albumYear, 2024);
        assert.strictEqual(parsed.albumType, 'album');
    });

    it('extrae embeddable=false y fila Music Album desde HTML de watch?v=...', () => {
        const playerResponse = {
            videoDetails: {
                title: "BABYMONSTER - 'DRIP' M/V",
                author: 'BABYMONSTER',
                shortDescription: 'BABYMONSTER 1st FULL ALBUM [DRIP]\nAvailable now!'
            },
            playabilityStatus: {
                status: 'OK',
                playableInEmbed: false
            },
            microformat: {
                playerMicroformatRenderer: {
                    publishDate: '2024-11-01'
                }
            }
        };

        const initialData = {
            engagementPanels: [
                {
                    panel: {
                        cards: [
                            {
                                infoRows: [
                                    { infoRowRenderer: { title: { simpleText: 'SONG' }, defaultMetadata: { simpleText: 'DRIP' } } },
                                    { infoRowRenderer: { title: { simpleText: 'ARTIST' }, defaultMetadata: { simpleText: 'BABYMONSTER' } } },
                                    { infoRowRenderer: { title: { simpleText: 'ALBUM' }, defaultMetadata: { simpleText: 'Drip' } } }
                                ]
                            }
                        ]
                    }
                }
            ]
        };

        const fakeHtml = `
            <html><head></head><body>
            <script>var ytInitialPlayerResponse = ${JSON.stringify(playerResponse)};</script>
            <script>var ytInitialData = ${JSON.stringify(initialData)};</script>
            </body></html>
        `;

        const watchMeta = extractYouTubeWatchPageMetadata(fakeHtml);
        assert.strictEqual(watchMeta.embeddable, false);
        assert.strictEqual(watchMeta.publishYear, 2024);
        assert.strictEqual(watchMeta.creditAlbum, 'Drip');

        const merged = mergeResolvedTrackMetadata({
            videoId: 'Zp-Jhuhq0bQ',
            oembed: { title: "BABYMONSTER - 'DRIP' M/V", author_name: 'BABYMONSTER' },
            watchMeta,
            catalogAlbums: [
                { id: 1, titulo: 'Drip', tipo_lanzamiento: 'album', anio: 2024, artista_principal_nombre: 'BABYMONSTER' }
            ],
            catalogSongs: []
        });

        assert.strictEqual(merged.suggestedTitle, 'DRIP');
        assert.strictEqual(merged.suggestedArtist, 'BABYMONSTER');
        assert.strictEqual(merged.suggestedAlbumTitle, 'Drip');
        assert.strictEqual(merged.suggestedAlbumType, 'album');
        assert.strictEqual(merged.suggestedAlbumYear, 2024);
        assert.strictEqual(merged.embeddable, false);
    });

    it('empareja álbum existente cuando el M/V coincide con title-track del mismo artista', () => {
        const merged = mergeResolvedTrackMetadata({
            videoId: 'abc12345678',
            oembed: { title: "BABYMONSTER - 'WE GO UP' M/V", author_name: 'BABYMONSTER' },
            watchMeta: null,
            catalogAlbums: [
                { id: 2, titulo: 'We go up', tipo_lanzamiento: 'mini_album', anio: 2025, artista_principal_nombre: 'BABYMONSTER' }
            ],
            catalogSongs: []
        });

        assert.strictEqual(merged.suggestedTitle, 'WE GO UP');
        assert.strictEqual(merged.suggestedArtist, 'BABYMONSTER');
        assert.strictEqual(merged.suggestedAlbumTitle, 'We go up');
        assert.strictEqual(merged.suggestedAlbumType, 'mini_album');
        assert.strictEqual(merged.suggestedAlbumYear, 2025);
    });

    it('limpia subtítulos .vtt, .srt y .lrc eliminando tiempos, etiquetas y duplicados consecutivos', () => {
        const sampleVtt = [
            'WEBVTT',
            'Kind: captions',
            'Language: en',
            '',
            '00:00:10.000 --> 00:00:12.500',
            '<c>Baby</c><00:00:10.400><c> got no</c> chill',
            '',
            '00:00:12.500 --> 00:00:14.000',
            'Baby got no chill',
            '',
            '00:00:14.000 --> 00:00:16.500',
            'I got that drip &amp; shine'
        ].join('\n');

        assert.strictEqual(
            cleanCaptionTextToLyrics(sampleVtt),
            'Baby got no chill\nI got that drip & shine'
        );

        const sampleLrc = '[ti:DRIP]\n[ar:BABYMONSTER]\n[00:15.20]Ooh look at me now\n[00:18.45]네 맘을 사로잡아';
        assert.strictEqual(
            cleanCaptionTextToLyrics(sampleLrc),
            'Ooh look at me now\n네 맘을 사로잡아'
        );
    });

    it('limpia formatos complejos (1theK _, 「」 japonés, ft. sin paréntesis), detecta canales genéricos e infiere idioma/año de estudio', () => {
        const iu = parseCleanTrackAndArtist('[MV] IU(아이유) _ Blueming(블루밍)', '1theK (원더케이)');
        assert.strictEqual(iu.mainArtist, 'IU(아이유)');
        assert.strictEqual(iu.title, 'Blueming(블루밍)');
        assert.strictEqual(iu.artistFromTitle, true);

        const yoasobi = parseCleanTrackAndArtist('YOASOBI「アイドル」 Official Music Video', 'Ayase / YOASOBI');
        assert.strictEqual(yoasobi.mainArtist, 'YOASOBI');
        assert.strictEqual(yoasobi.title, 'アイドル');

        const bruno = parseCleanTrackAndArtist('Bruno Mars - Die With A Smile ft. Lady Gaga (Official Video)', 'Bruno Mars');
        assert.strictEqual(bruno.mainArtist, 'Bruno Mars');
        assert.strictEqual(bruno.title, 'Die With A Smile');
        assert.deepStrictEqual(bruno.collaborators, ['Lady Gaga']);

        assert.strictEqual(isGenericUploaderChannel('1theK (원더케이)'), true);
        assert.strictEqual(isGenericUploaderChannel('HYBE LABELS'), true);
        assert.strictEqual(isGenericUploaderChannel('7clouds'), true);
        assert.strictEqual(isGenericUploaderChannel('Jaeguchi'), true);
        assert.strictEqual(isGenericUploaderChannel('BABYMONSTER'), false);

        const hintsP = parseGeneralDescriptionAlbumHints('Music by EDAM\n℗ 2021 EDAM Entertainment');
        assert.strictEqual(hintsP.albumYear, 2021);
        const hintsC = parseGeneralDescriptionAlbumHints('© 2019 YG Entertainment Inc.');
        assert.strictEqual(hintsC.albumYear, 2019);

        assert.strictEqual(inferSuggestedSongLanguage({ title: 'Shape of You', artist: 'Ed Sheeran' }), 'English');
        assert.strictEqual(inferSuggestedSongLanguage({ title: '밤편지', artist: '아이유' }), 'Korean');
        assert.strictEqual(inferSuggestedSongLanguage({ title: 'Blueming(블루밍)', artist: 'IU' }), 'English + Korean (K-Pop)');
        assert.strictEqual(inferSuggestedSongLanguage({ title: 'DRIP', artist: 'BABYMONSTER', genre: 'K-Pop' }), 'English + Korean (K-Pop)');
        assert.strictEqual(inferSuggestedSongLanguage({ title: 'アイドル', artist: 'YOASOBI' }), 'Japanese');
        assert.strictEqual(inferSuggestedSongLanguage({ title: '夜に駆ける (English Ver.)', artist: 'YOASOBI', genre: 'J-Pop' }), 'English + Japanese (J-Pop)');
        assert.strictEqual(inferSuggestedSongLanguage({ title: 'La Canción', artist: 'J Balvin', genre: 'Urbano latino' }), 'Spanish');

        // Año oficial externo (2019) vence a subida tardía de YouTube (2025), hereda artistType y marca single duplicado
        const merged = mergeResolvedTrackMetadata({
            videoId: 'abc99999999',
            oembed: { title: 'Blueming (Color Coded Lyrics)', author_name: 'Color Coded Lyrics' },
            watchMeta: { rawTitle: 'Blueming (Color Coded Lyrics)', rawAuthor: 'Color Coded Lyrics', publishYear: 2025 },
            externalMeta: {
                title: 'Blueming',
                artist: 'IU',
                collaborators: [],
                albumTitle: 'Blueming - Single',
                albumType: 'single',
                releaseYear: 2019,
                trackNumber: 1,
                genre: 'K-Pop',
                source: 'itunes'
            },
            catalogArtists: [{ id: 10, nombre: 'IU', tipo_artista: 'solo' }],
            catalogAlbums: [],
            catalogSongs: []
        });
        assert.strictEqual(merged.suggestedTitle, 'Blueming');
        assert.strictEqual(merged.suggestedArtist, 'IU');
        assert.strictEqual(merged.suggestedAlbumYear, 2019);
        assert.strictEqual(merged.suggestedArtistType, 'solo');
        assert.strictEqual(merged.suggestedLanguage, 'English + Korean (K-Pop)');
        assert.strictEqual(merged.suggestedTrackNumber, 1);
        assert.strictEqual(merged.suggestedAlbumIsSingleDuplicate, true);
    });
});
