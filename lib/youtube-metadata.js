/**
 * Detect generic label, distributor, lyric, or variety channels that should not replace the real song artist.
 * @param {string} channelName
 * @returns {boolean}
 */
function isGenericUploaderChannel(channelName) {
    const cleaned = String(channelName || '')
        .replace(/\s*-\s*Topic$/i, '')
        .replace(/\s+(?:VEVO|Official(?:\s+Channel)?)$/i, '')
        .replace(/\s+/g, ' ')
        .trim()
        .toLowerCase();
    if (!cleaned) return false;
    if (GENERIC_UPLOADER_EXACT.has(cleaned)) return true;
    return (
        /^1thek(?:\s|$)/i.test(cleaned) ||
        /^stone\s+music/i.test(cleaned) ||
        /^genie\s+music/i.test(cleaned) ||
        /\b(?:color\s*coded|lyric\s*videos?|sub\s+espa[nñ]ol)\b/i.test(cleaned) ||
        /\s+lyrics?$/i.test(cleaned) ||
        /\s+letras?$/i.test(cleaned)
    );
}

/**
 * Clean decorative YouTube title noise without losing real song or artist text.
 * @param {string} rawTitle
 * @returns {string}
 */
function cleanRawYouTubeTitleNoise(rawTitle) {
    let working = decodeHtmlEntities(String(rawTitle || ''))
        .replace(/(?:\u2764\uFE0F?|[\u{1F3B5}-\u{1F3BC}\u{1F525}\u{1F4A5}\u{1F49C}\u{1F5A4}\u{1F90D}\u{1F4AB}\u{1F3AC}\u{1F3A7}\u{1F3A4}\u2728\u2B50])/gu, ' ')
        .replace(/\s+/g, ' ')
        .trim();

    const perfChannelNoise = /\s*(?:\/|\||[-–—])\s*(?:THE\s+FIRST\s+TAKE|COLORS\s*(?:SHOW|x\s*STUDIOS)?|tiny\s+desk\s+concert|it'?s\s+Live|STUDIO\s+CHOOM)\s*$/i;
    for (let pass = 0; pass < 3; pass += 1) {
        const prev = working;
        for (const pat of TITLE_NOISE_PATTERNS) {
            working = working.replace(pat, '');
        }
        working = working.replace(perfChannelNoise, '').replace(/\s+/g, ' ').trim();
        if (working === prev) break;
    }
    return working;
}

/**
 * Decode minimal HTML/XML entities common in YouTube HTML metadata and captions.
 * @param {string} value
 * @returns {string}
 */
function decodeHtmlEntities(value) {
    return String(value || '')
        .replace(/&amp;/g, '&')
        .replace(/&quot;/g, '"')
        .replace(/&#39;|&apos;/g, "'")
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')
        .replace(/&nbsp;/gi, ' ')
        .replace(/&#(\d+);/g, (_m, dec) => {
            const code = Number(dec);
            return Number.isFinite(code) && code > 0 && code < 0x10ffff ? String.fromCodePoint(code) : '';
        })
        .replace(/\\u([0-9a-fA-F]{4})/g, (_m, hex) => String.fromCharCode(parseInt(hex, 16)));
}

/**
 * Normalize text for fuzzy matching against the user's catalog.
 * @param {string} value
 * @returns {string}
 */
function normalizeLookupText(value) {
    return String(value || '')
        .normalize('NFKC')
        .trim()
        .toLowerCase()
        .replace(/[\u2018\u2019\u201c\u201d"'`´]/g, '')
        .replace(/\s+/g, ' ');
}

/**
 * Strip surrounding single/double/smart quotes from a track title.
 * @param {string} text
 * @returns {string}
 */
function stripOuterQuotes(text) {
    let out = String(text || '').trim();
    if (
        (out.startsWith("'") && out.endsWith("'")) ||
        (out.startsWith('"') && out.endsWith('"')) ||
        (out.startsWith('“') && out.endsWith('”')) ||
        (out.startsWith('‘') && out.endsWith('’')) ||
        (out.startsWith('[') && out.endsWith(']') && !out.includes('] ['))
    ) {
        out = out.slice(1, -1).trim();
    }
    return out;
}

/**
 * Infer release type (`album`, `mini_album`, `ep`, `single`, `collab_single`, `ost`) from free text.
 * @param {string} text
 * @returns {string}
 */
function inferReleaseType(text) {
    const lower = String(text || '').toLowerCase();
    if (!lower) return 'album';
    if (/\bost\b|original\s+soundtrack|soundtrack/.test(lower)) return 'ost';
    if (/mini[\s_-]*album|미니\s*앨범|\bmini\b/.test(lower)) return 'mini_album';
    if (/\bep\b|extended\s+play/.test(lower)) return 'ep';
    if (/\bsingle\b|digital\s+single|pre-release\s+single|싱글/.test(lower)) return 'single';
    return 'album';
}

/**
 * Split an artist string into main artist and collaborators (`&`, `x`, `feat.`, `ft.`, `with`).
 * Avoids breaking legitimate band names when only a standalone channel is given unless separators match.
 * @param {string} rawArtist
 * @returns {{ mainArtist: string, collaborators: string[] }}
 */
function splitArtistCredits(rawArtist) {
    const cleaned = String(rawArtist || '')
        .replace(/\s*-\s*Topic$/i, '')
        .replace(/\s+(?:VEVO|Official(?:\s+Channel)?)$/i, '')
        .replace(/\s+/g, ' ')
        .trim();

    if (!cleaned) return { mainArtist: '', collaborators: [] };

    const featMatch = cleaned.match(/^(.+?)\s+(?:feat\.?|ft\.?|featuring)\s+(.+)$/i);
    if (featMatch) {
        const extra = featMatch[2]
            .split(/\s*[,&]\s*/)
            .map(s => s.trim())
            .filter(Boolean);
        return { mainArtist: featMatch[1].trim(), collaborators: extra };
    }

    const duetMatch = cleaned.match(/^(.+?)\s+(?:&|×|\bx\b|\bwith\b)\s+(.+)$/i);
    if (duetMatch && duetMatch[1].trim().length >= 2 && duetMatch[2].trim().length >= 2) {
        const collabs = duetMatch[2]
            .split(/\s*[,&]\s*/)
            .map(s => s.trim())
            .filter(Boolean);
        return { mainArtist: duetMatch[1].trim(), collaborators: collabs };
    }

    return { mainArtist: cleaned, collaborators: [] };
}

function stripTrailingBareCollabFromTitle(rawTitle, collaborators) {
    const clean = stripOuterQuotes(rawTitle);
    const bareMatch = clean.match(/^(.{1,140}?)\s+(?:feat\.?|ft\.?|featuring|w\/)\s+(.{1,120})$/i);
    if (!bareMatch) return clean;
    bareMatch[2]
        .split(/\s*[,&]\s*/)
        .map(s => s.trim())
        .filter(Boolean)
        .forEach(c => {
            if (!collaborators.includes(c)) collaborators.push(c);
        });
    return stripOuterQuotes(bareMatch[1]);
}

/**
 * Clean a raw YouTube / YT Music title and channel author into track title, main artist, and collaborators.
 * Examples handled:
 * - "BABYMONSTER - 'DRIP' M/V" -> title: "DRIP", mainArtist: "BABYMONSTER"
 * - "ROSÉ & Bruno Mars - APT. (Official Music Video)" -> title: "APT.", mainArtist: "ROSÉ", collabs: ["Bruno Mars"]
 * - "[MV] IU(아이유) _ Blueming(블루밍)" -> title: "Blueming(블루밍)", mainArtist: "IU(아이유)"
 * - "YOASOBI「アイドル」 Official Music Video" -> title: "アイドル", mainArtist: "YOASOBI"
 * @param {string} rawTitle
 * @param {string} rawChannel
 * @returns {{ title: string, mainArtist: string, collaborators: string[], artistFromTitle?: boolean }}
 */
function parseCleanTrackAndArtist(rawTitle, rawChannel) {
    let working = cleanRawYouTubeTitleNoise(rawTitle);
    const channelRawClean = decodeHtmlEntities(String(rawChannel || ''));
    const channelIsGeneric = isGenericUploaderChannel(channelRawClean);
    const channelCredit = channelIsGeneric
        ? { mainArtist: '', collaborators: [] }
        : splitArtistCredits(channelRawClean);
    const collaborators = [...channelCredit.collaborators];

    let title = working;
    let mainArtist = channelCredit.mainArtist;
    let artistFromTitle = false;

    // Extract `(feat. X)`, `[ft. X]`, `(with X)`, `(w/ X)` embedded in song title before splitting.
    const titleFeatRe = /\s*[\[(]\s*(?:feat\.?|ft\.?|featuring|with|w\/)\s+([^\]()]+)[\])]/gi;
    let featHit;
    while ((featHit = titleFeatRe.exec(working)) !== null) {
        featHit[1]
            .split(/\s*[,&]\s*/)
            .map(s => s.trim())
            .filter(Boolean)
            .forEach(c => {
                if (!collaborators.includes(c)) collaborators.push(c);
            });
    }
    working = working.replace(titleFeatRe, '').replace(/\s+/g, ' ').trim();

    // Pattern 1: "Artist - Song" (en-dash, em-dash, or hyphen)
    const dashMatch = working.match(/^(.{1,90}?)\s+[-–—]\s+(.{1,160})$/);
    if (dashMatch) {
        const parsedArtist = splitArtistCredits(dashMatch[1]);
        if (parsedArtist.mainArtist) {
            mainArtist = parsedArtist.mainArtist;
            artistFromTitle = true;
            parsedArtist.collaborators.forEach(c => {
                if (!collaborators.includes(c)) collaborators.push(c);
            });
        }
        title = stripTrailingBareCollabFromTitle(dashMatch[2], collaborators);
    } else {
        // Pattern 2: "Artist _ Song" (1theK / Stone Music style)
        const underscoreMatch = working.match(/^(.{1,90}?)\s+_\s+(.{1,160})$/);
        if (underscoreMatch) {
            const parsedArtist = splitArtistCredits(underscoreMatch[1]);
            if (parsedArtist.mainArtist) {
                mainArtist = parsedArtist.mainArtist;
                artistFromTitle = true;
                parsedArtist.collaborators.forEach(c => {
                    if (!collaborators.includes(c)) collaborators.push(c);
                });
            }
            title = stripTrailingBareCollabFromTitle(underscoreMatch[2], collaborators);
        } else {
            // Pattern 3: "Artist「Song」" / "Artist『Song』" (J-Pop / Anime style)
            const jpBracketMatch = working.match(/^(.{1,70}?)\s*[「『]([^」』]{1,120})[」』]\s*(.*)$/);
            if (jpBracketMatch) {
                const parsedArtist = splitArtistCredits(jpBracketMatch[1]);
                if (parsedArtist.mainArtist) {
                    mainArtist = parsedArtist.mainArtist;
                    artistFromTitle = true;
                    parsedArtist.collaborators.forEach(c => {
                        if (!collaborators.includes(c)) collaborators.push(c);
                    });
                }
                if (jpBracketMatch[3]) {
                    stripTrailingBareCollabFromTitle(`x ${jpBracketMatch[3]}`, collaborators);
                }
                title = jpBracketMatch[2].trim();
            } else {
                // Pattern 4: "Artist 'Song Title'" (common in SM / K-Pop M/V titles)
                const quotedMatch = working.match(/^(.{1,70}?)\s+['"‘“]([^'"’”]{1,120})['"’”]\s*$/);
                if (quotedMatch) {
                    const parsedArtist = splitArtistCredits(quotedMatch[1]);
                    if (parsedArtist.mainArtist) {
                        mainArtist = parsedArtist.mainArtist;
                        artistFromTitle = true;
                        parsedArtist.collaborators.forEach(c => {
                            if (!collaborators.includes(c)) collaborators.push(c);
                        });
                    }
                    title = stripTrailingBareCollabFromTitle(quotedMatch[2], collaborators);
                } else {
                    // Pattern 5: "Song | Artist" when channel is generic or matches right side
                    const pipeMatch = working.match(/^(.{1,120}?)\s*\|\s*(.{1,80})$/);
                    const rightNorm = pipeMatch ? normalizeLookupText(pipeMatch[2]) : '';
                    const chanNorm = normalizeLookupText(channelCredit.mainArtist);
                    if (pipeMatch && !isGenericUploaderChannel(pipeMatch[2]) && (channelIsGeneric || (chanNorm && (rightNorm.includes(chanNorm) || chanNorm.includes(rightNorm))))) {
                        const parsedArtist = splitArtistCredits(pipeMatch[2]);
                        if (parsedArtist.mainArtist) {
                            mainArtist = parsedArtist.mainArtist;
                            artistFromTitle = true;
                            parsedArtist.collaborators.forEach(c => {
                                if (!collaborators.includes(c)) collaborators.push(c);
                            });
                        }
                        title = stripTrailingBareCollabFromTitle(pipeMatch[1], collaborators);
                    } else {
                        title = stripTrailingBareCollabFromTitle(working, collaborators);
                    }
                }
            }
        }
    }

    const dedupedCollabs = [];
    const mainNorm = normalizeLookupText(mainArtist);
    const seen = new Set(mainNorm ? [mainNorm] : []);
    for (const c of collaborators) {
        const norm = normalizeLookupText(c);
        if (!norm || seen.has(norm)) continue;
        seen.add(norm);
        dedupedCollabs.push(c);
    }

    return {
        title: title.slice(0, 180),
        mainArtist: mainArtist.slice(0, 140),
        collaborators: dedupedCollabs,
        artistFromTitle
    };
}

/**
 * Parse YouTube Music "Provided to YouTube by ..." Art Track description blocks.
 * Standard block format:
 *   Provided to YouTube by <Distributor>
 *   <Track> · <Artist 1> · <Artist 2>
 *   <Album Title>
 *   ℗ <Label>
 *   Released on: YYYY-MM-DD
 * @param {string} description
 * @returns {{ title: string|null, mainArtist: string|null, collaborators: string[], albumTitle: string|null, albumType: string|null, albumYear: number|null } | null}
 */
function parseProvidedToYouTubeDescription(description) {
    const raw = String(description || '');
    if (!/Provided to YouTube by/i.test(raw)) return null;

    const lines = raw
        .split(/\r?\n/)
        .map(line => line.trim())
        .filter(Boolean);

    const headerIdx = lines.findIndex(line => /^Provided to YouTube by/i.test(line));
    if (headerIdx < 0) return null;

    let title = null;
    let mainArtist = null;
    const collaborators = [];
    let albumTitle = null;
    let albumYear = null;

    const afterHeader = lines.slice(headerIdx + 1);
    const creditLine = afterHeader[0] || '';
    if (creditLine && !/^[℗©]/.test(creditLine) && !/^Released on:/i.test(creditLine)) {
        const parts = creditLine.split(/\s+·\s+/).map(p => p.trim()).filter(Boolean);
        title = parts[0] || null;
        if (parts.length > 1) {
            const firstArtist = splitArtistCredits(parts[1]);
            mainArtist = firstArtist.mainArtist || parts[1];
            firstArtist.collaborators.forEach(c => collaborators.push(c));
            parts.slice(2).forEach(extra => {
                const splitExtra = splitArtistCredits(extra);
                if (splitExtra.mainArtist) collaborators.push(splitExtra.mainArtist);
                splitExtra.collaborators.forEach(c => collaborators.push(c));
            });
        }
    }

    const potentialAlbumLine = afterHeader[1] || '';
    if (
        potentialAlbumLine &&
        !/^[℗©]/.test(potentialAlbumLine) &&
        !/^(?:Released on:|Auto-generated by YouTube|Composer:|Lyricist:|Producer:|Main\s+Artist:)/i.test(potentialAlbumLine)
    ) {
        albumTitle = potentialAlbumLine.slice(0, 180);
    }

    let releaseDate = null;
    const releasedMatch = raw.match(/Released on:\s*((\d{4})-\d{2}-\d{2})/i);
    if (releasedMatch) {
        releaseDate = releasedMatch[1];
        const parsedYear = Number(releasedMatch[2]);
        if (parsedYear >= 1900 && parsedYear <= 2100) albumYear = parsedYear;
    }

    return {
        title: title ? title.slice(0, 180) : null,
        mainArtist: mainArtist ? mainArtist.slice(0, 140) : null,
        collaborators,
        albumTitle,
        albumType: albumTitle ? inferReleaseType(`${albumTitle} ${raw}`) : null,
        albumYear,
        releaseDate
    };
}

/**
 * Parse general video description cues for album name, release year, and release type.
 * Useful on official M/Vs (e.g. "BABYMONSTER 1st FULL ALBUM [DRIP]", "Album: DRIP").
 * @param {string} description
 * @returns {{ albumTitle: string|null, albumType: string|null, albumYear: number|null }}
 */
function parseGeneralDescriptionAlbumHints(description) {
    const raw = String(description || '');
    if (!raw.trim()) return { albumTitle: null, albumType: null, albumYear: null };

    let albumTitle = null;
    let albumType = null;
    let albumYear = null;

    const explicitAlbumLine = raw.match(/(?:^|\n)\s*(?:Album|Mini\s+Album|EP|OST|앨범)\s*[:：]\s*([^\n\r]{2,120})/i);
    if (explicitAlbumLine) {
        albumTitle = stripOuterQuotes(explicitAlbumLine[1].replace(/\s*[-–|].*$/, '').trim()).slice(0, 180);
        albumType = inferReleaseType(explicitAlbumLine[0]);
    }

    if (!albumTitle) {
        const promoMatch = raw.match(
            /(?:1st|2nd|3rd|\d+th)?\s*(?:Full|Mini|Digital)?\s*(Mini\s+Album|Album|EP|Single|OST)\s*[\["'‘“]([^\]"'’”\n]{1,100})[\]"'’”]/i
        );
        if (promoMatch) {
            albumType = inferReleaseType(promoMatch[1]);
            albumTitle = promoMatch[2].trim().slice(0, 180);
        }
    }

    if (!albumTitle) {
        const fromAlbumMatch = raw.match(/from\s+(?:the\s+)?(?:upcoming\s+)?(?:new\s+)?(?:album|mini[\s-]album|ep)\s*['"‘“]([^'"’”\n]{1,100})['"’”]/i);
        if (fromAlbumMatch) {
            albumType = inferReleaseType(fromAlbumMatch[0]);
            albumTitle = fromAlbumMatch[1].trim().slice(0, 180);
        }
    }

    // Explicit date markers (EN / ES / KO / JA)
    const yearPatterns = [
        /(?:Released on|Release\s*date|Release|Published\s*on|Fecha\s+de\s+lanzamiento|발매일|発売日)\s*[:：]?\s*(?:[A-Za-z]{3,9}\s+\d{1,2},?\s*)?(\d{4})/i,
        /[℗©]\s*(\d{4})\b/,
        /\((?:P|C)\)\s*(\d{4})\b/i,
        /[℗©][^\n]{0,45}\b((?:19\d{2}|20[0-3]\d))\b/
    ];
    for (const pat of yearPatterns) {
        const m = raw.match(pat);
        if (m) {
            const yr = Number(m[1]);
            if (yr >= 1900 && yr <= 2100) {
                albumYear = yr;
                break;
            }
        }
    }

    return {
        albumTitle: albumTitle || null,
        albumType: albumType && VALID_RELEASE_TYPES.has(albumType) ? albumType : null,
        albumYear
    };
}

/**
 * Clean single/EP suffixes returned by iTunes/MusicBrainz (e.g. "APT. - Single") and adjust release type.
 * @param {string|null} rawAlbumTitle
 * @param {string|null} currentType
 * @returns {{ albumTitle: string|null, albumType: string|null }}
 */
function normalizeAlbumTitleAndType(rawAlbumTitle, currentType = null) {
    let albumTitle = String(rawAlbumTitle || '').trim();
    let albumType = currentType && VALID_RELEASE_TYPES.has(currentType) ? currentType : null;
    if (!albumTitle) return { albumTitle: null, albumType };

    if (/\s*[-–—]\s*Single\s*$/i.test(albumTitle)) {
        albumTitle = albumTitle.replace(/\s*[-–—]\s*Single\s*$/i, '').trim();
        if (!albumType || albumType === 'album') albumType = 'single';
    } else if (/\s*[-–—]\s*EP\s*$/i.test(albumTitle)) {
        albumTitle = albumTitle.replace(/\s*[-–—]\s*EP\s*$/i, '').trim();
        if (!albumType || albumType === 'album') albumType = 'ep';
    }

    return {
        albumTitle: albumTitle ? albumTitle.slice(0, 180) : null,
        albumType
    };
}

/**
 * Infer one of `#musicSongLanguage`'s canonical options from title, artist, genre, and description cues.
 * Returns one of: 'English', 'Korean', 'English + Korean (K-Pop)', 'Japanese',
 * 'English + Japanese (J-Pop)', 'Spanish', 'Other'.
 * @param {object} [params]
 * @returns {string}
 */
function inferSuggestedSongLanguage({ title = '', rawTitle = '', artist = '', description = '', genre = '' } = {}) {
    const cleanTitleStr = cleanRawYouTubeTitleNoise(title || rawTitle);
    const titleAndRaw = `${cleanTitleStr} ${cleanRawYouTubeTitleNoise(rawTitle)}`.trim();
    const genreLower = String(genre || '').trim().toLowerCase();
    const descHead = String(description || '').slice(0, 800);

    const hasHangul = (s) => /[\uAC00-\uD7A3\u1100-\u11FF\u3130-\u318F]/.test(String(s || ''));
    const hasKana = (s) => /[\u3040-\u309F\u30A0-\u30FF]/.test(String(s || ''));
    const hasKanji = (s) => /[\u4E00-\u9FFF]/.test(String(s || ''));
    const hasMeaningfulLatin = (s) => /[A-Za-z]{2,}/.test(
        String(s || '').replace(/\b(?:ft|feat|ver|mv|ost|ep)\b/gi, '')
    );

    const hangulCountInDesc = (descHead.match(/[\uAC00-\uD7A3]/g) || []).length;
    const kanaCountInDesc = (descHead.match(/[\u3040-\u309F\u30A0-\u30FF]/g) || []).length;

    const isKpopGenre = /\bk-?pop\b|korean/i.test(genreLower);
    const isJpopGenre = /\bj-?pop\b|anime|japanese|kayokyoku/i.test(genreLower);
    const isLatinGenre = /\b(?:latin|urbano\s+latino|pop\s+latino|rock\s+y\s+alternativo|reggaeton|regional\s+mexicano|salsa|bachata|cumbia|spanish|espa[nñ]ol)\b/i.test(genreLower);

    const hasKoSignal = hasHangul(titleAndRaw) || hasHangul(artist) || isKpopGenre || hangulCountInDesc >= 6;
    if (hasKoSignal) {
        const titleForLatin = cleanRawYouTubeTitleNoise(title || '') || cleanTitleStr;
        if (hasMeaningfulLatin(titleForLatin)) {
            return 'English + Korean (K-Pop)';
        }
        return 'Korean';
    }

    const hasJaSignal =
        hasKana(titleAndRaw) ||
        hasKana(artist) ||
        isJpopGenre ||
        kanaCountInDesc >= 4 ||
        ((hasKanji(titleAndRaw) || hasKanji(artist)) && (kanaCountInDesc >= 2 || /発売日|歌詞/.test(descHead)));
    if (hasJaSignal) {
        const titleForLatin = cleanRawYouTubeTitleNoise(title || '') || cleanTitleStr;
        if (hasMeaningfulLatin(titleForLatin)) {
            return 'English + Japanese (J-Pop)';
        }
        return 'Japanese';
    }

    const spanishCueRe = /\b(?:coraz[oó]n|amor|noche|siempre|contigo|conmigo|quiero|vida|beso|sola|solo|canci[oó]n|perd[oó]n|m[ií]o|tuyo|tuya|baila|llorar|soledad)\b/i;
    const nonAsciiAccents = /[áéíóúüñ¿¡]/i;
    const hasEsSignal =
        isLatinGenre ||
        nonAsciiAccents.test(titleAndRaw) ||
        nonAsciiAccents.test(artist) ||
        spanishCueRe.test(titleAndRaw);
    if (hasEsSignal && !hasHangul(descHead) && !hasKana(descHead)) {
        return 'Spanish';
    }

    if (/[A-Za-z]/.test(`${cleanTitleStr} ${artist}`)) {
        return 'English';
    }
    return 'Other';
}

/**
 * Extract a balanced JSON object assigned to a variable (e.g. `ytInitialPlayerResponse = {...}`)
 * without loading or parsing the rest of a huge HTML page.
 * @param {string} html
 * @param {string} varName
 * @returns {object|null}
 */
function extractAssignedJsonObject(html, varName) {
    if (!html || !varName) return null;
    const escapedName = varName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const match = new RegExp(`(?:var\\s+|window\\["${escapedName}"\\]\\s*=\\s*|${escapedName}\\s*=\\s*)(\\{)`).exec(html);
    if (!match) return null;

    const startIdx = match.index + match[0].length - 1;
    let depth = 0;
    let inString = false;
    let escaped = false;
    const maxScan = Math.min(html.length, startIdx + 450000);

    for (let i = startIdx; i < maxScan; i++) {
        const ch = html[i];
        if (inString) {
            if (escaped) {
                escaped = false;
            } else if (ch === '\\') {
                escaped = true;
            } else if (ch === '"') {
                inString = false;
            }
            continue;
        }
        if (ch === '"') {
            inString = true;
        } else if (ch === '{') {
            depth++;
        } else if (ch === '}') {
            depth--;
            if (depth === 0) {
                const jsonSlice = html.slice(startIdx, i + 1);
                try {
                    return JSON.parse(jsonSlice);
                } catch (_err) {
                    return null;
                }
            }
        }
    }
    return null;
}

/**
 * Recursively find `"Song"` / `"Artist"` / `"Album"` credit rows inside `ytInitialData`
 * (the "Music in this video" info rows on YouTube watch pages).
 * @param {any} node
 * @param {object} acc
 * @param {number} depth
 */
function collectMusicCreditRows(node, acc, depth = 0) {
    if (!node || typeof node !== 'object' || depth > 22) return;
    if (acc.album && acc.song && acc.artist) return;

    if (node.infoRowRenderer && typeof node.infoRowRenderer === 'object') {
        const row = node.infoRowRenderer;
        const label = String(row.title?.simpleText || row.title?.runs?.[0]?.text || '').trim().toLowerCase();
        const val = String(
            row.defaultMetadata?.simpleText ||
            (Array.isArray(row.defaultMetadata?.runs) ? row.defaultMetadata.runs.map(r => r.text).join('') : '') ||
            ''
        ).trim();
        if (val) {
            if ((label === 'album' || label === 'álbum' || label === '앨범') && !acc.album) acc.album = val;
            if ((label === 'song' || label === 'canción' || label === '노래') && !acc.song) acc.song = val;
            if ((label === 'artist' || label === 'artista' || label === '아티스트') && !acc.artist) acc.artist = val;
        }
    }

    if (Array.isArray(node)) {
        for (const item of node) {
            collectMusicCreditRows(item, acc, depth + 1);
            if (acc.album && acc.song && acc.artist) break;
        }
        return;
    }

    for (const key of Object.keys(node)) {
        if (key === 'contents' || key === 'engagementPanels' || key === 'structuredDescriptionContentRenderer' || key === 'horizontalCardListRenderer' || key === 'cards' || key === 'items' || key === 'infoRows' || key === 'videoDescriptionMusicSectionRenderer' || key === 'carouselLockups' || key === 'twoColumnWatchNextResults' || key === 'secondaryResults' || key === 'panel' || key === 'content') {
            collectMusicCreditRows(node[key], acc, depth + 1);
        }
    }
}

/**
 * Extract rich track metadata and embeddability from a YouTube `watch?v=...` HTML response.
 * @param {string} html
 * @returns {{ rawTitle: string|null, rawAuthor: string|null, description: string, publishYear: number|null, embeddable: boolean|null, creditSong: string|null, creditArtist: string|null, creditAlbum: string|null }}
 */
function extractYouTubeWatchPageMetadata(html) {
    const out = {
        rawTitle: null,
        rawAuthor: null,
        description: '',
        publishYear: null,
        embeddable: null,
        creditSong: null,
        creditArtist: null,
        creditAlbum: null,
        publishDate: null
    };
    if (!html || typeof html !== 'string') return out;

    const playerResp = extractAssignedJsonObject(html, 'ytInitialPlayerResponse');
    if (playerResp && typeof playerResp === 'object') {
        const details = playerResp.videoDetails || {};
        const micro = playerResp.microformat?.playerMicroformatRenderer || {};
        const playability = playerResp.playabilityStatus || {};

        if (details.title || micro.title?.simpleText) {
            out.rawTitle = String(details.title || micro.title.simpleText).trim();
        }
        if (details.author || micro.ownerChannelName) {
            out.rawAuthor = String(details.author || micro.ownerChannelName).trim();
        }
        if (details.shortDescription || micro.description?.simpleText) {
            out.description = String(details.shortDescription || micro.description.simpleText);
        }
        const dateStr = String(micro.publishDate || micro.uploadDate || '');
        const fullDateMatch = dateStr.match(/^(\d{4}-\d{2}-\d{2})/);
        if (fullDateMatch) out.publishDate = fullDateMatch[1];
        const dateYear = dateStr.match(/^(\d{4})/);
        if (dateYear) {
            const yr = Number(dateYear[1]);
            if (yr >= 1900 && yr <= 2100) out.publishYear = yr;
        }
        if (typeof playability.playableInEmbed === 'boolean') {
            out.embeddable = playability.playableInEmbed;
        } else if (micro.embed && typeof micro.embed.iframeUrl === 'string') {
            out.embeddable = true;
        }
    } else {
        // Fallback lightweight meta/regex scan when full object wasn't balanced cleanly.
        const embedMatch = html.match(/"playableInEmbed"\s*:\s*(true|false)/);
        if (embedMatch) out.embeddable = embedMatch[1] === 'true';

        const ogTitle = html.match(/<meta\s+(?:property="og:title"|name="title")\s+content="([^"]+)"/i);
        if (ogTitle) out.rawTitle = decodeHtmlEntities(ogTitle[1]).trim();
    }

    // Look for "Music in this video" Song / Artist / Album lockup rows inside ytInitialData.
    const initialData = extractAssignedJsonObject(html, 'ytInitialData');
    if (initialData && typeof initialData === 'object') {
        const acc = { song: null, artist: null, album: null };
        collectMusicCreditRows(initialData, acc);
        out.creditSong = acc.song || null;
        out.creditArtist = acc.artist || null;
        out.creditAlbum = acc.album || null;
    } else {
        // Compact JSON pattern fallback for Album infoRowRenderer
        const albumCreditRegex = /"title"\s*:\s*\{"simpleText"\s*:\s*"(?:Album|Álbum|앨범)"\s*\}\s*,\s*"defaultMetadata"\s*:\s*\{[^}]*?"(?:simpleText|text)"\s*:\s*"([^"\\]{1,150})"/i;
        const mAlbum = html.match(albumCreditRegex);
        if (mAlbum) out.creditAlbum = decodeHtmlEntities(mAlbum[1]).trim();
    }

    return out;
}

/**
 * Combine oEmbed, optional YouTube Data API v3 item, watch HTML metadata, YT Music InnerTube,
 * external studio metadata (iTunes/MusicBrainz), optional yt-dlp metadata, and user's MySQL catalog
 * into a unified, clean suggestion payload for Auto-fill.
 * @param {object} params
 * @param {string|null} [params.videoId]
 * @param {object|null} [params.oembed]
 * @param {object|null} [params.apiVideo] YouTube Data API v3 `videos` item (`snippet`, `status`)
 * @param {object|null} [params.watchMeta] Result from `extractYouTubeWatchPageMetadata`
 * @param {object|null} [params.ytmMeta] Result from `fetchYouTubeMusicTrackMetadata`
 * @param {object|null} [params.externalMeta] Result from `fetchExternalTrackMetadata`
 * @param {object|null} [params.ytdlpMeta] Result from `fetchVideoMetadataViaYtDlp`
 * @param {Array<object>} [params.catalogSongs] User's existing songs
 * @param {Array<object>} [params.catalogAlbums] User's existing albums
 * @param {Array<object>} [params.catalogArtists] User's existing artists
 * @returns {object}
 */
function mergeResolvedTrackMetadata({
    videoId = null,
    oembed = null,
    apiVideo = null,
    watchMeta = null,
    ytmMeta = null,
    externalMeta = null,
    ytdlpMeta = null,
    catalogSongs = [],
    catalogAlbums = [],
    catalogArtists = []
}) {
    const metadataSources = [];
    if (oembed) metadataSources.push('oembed');
    if (apiVideo) metadataSources.push('youtube-api');
    if (watchMeta && (watchMeta.rawTitle || watchMeta.description || watchMeta.creditSong)) {
        metadataSources.push('youtube-watch');
    }
    if (ytmMeta && (ytmMeta.title || ytmMeta.artist || ytmMeta.year)) {
        metadataSources.push('ytmusic-innertube');
    }
    if (externalMeta && (externalMeta.title || externalMeta.artist || externalMeta.releaseYear)) {
        metadataSources.push(externalMeta.source ? `external:${externalMeta.source}` : 'external-meta');
    }
    if (ytdlpMeta && (ytdlpMeta.title || ytdlpMeta.track || ytdlpMeta.artist)) {
        metadataSources.push('yt-dlp');
    }

    const rawTitle =
        (apiVideo && apiVideo.snippet && apiVideo.snippet.title) ||
        (watchMeta && watchMeta.rawTitle) ||
        (ytdlpMeta && ytdlpMeta.title) ||
        (oembed && oembed.title) ||
        '';

    const rawChannel =
        (apiVideo && apiVideo.snippet && apiVideo.snippet.channelTitle) ||
        (watchMeta && watchMeta.rawAuthor) ||
        (oembed && oembed.author_name) ||
        (ytdlpMeta && ytdlpMeta.channel) ||
        '';

    const description =
        (apiVideo && apiVideo.snippet && apiVideo.snippet.description) ||
        (watchMeta && watchMeta.description) ||
        (ytdlpMeta && ytdlpMeta.description) ||
        '';

    const cleanFromTitle = parseCleanTrackAndArtist(rawTitle, rawChannel);
    const providedTrack = parseProvidedToYouTubeDescription(description);
    const descHints = parseGeneralDescriptionAlbumHints(description);
    if (providedTrack) metadataSources.push('provided-description');

    const ytmClean = ytmMeta && ytmMeta.title
        ? parseCleanTrackAndArtist(ytmMeta.title, ytmMeta.artist || rawChannel)
        : null;
    const ytdlpTrackClean = ytdlpMeta && ytdlpMeta.track
        ? cleanRawYouTubeTitleNoise(ytdlpMeta.track)
        : '';

    let title = cleanFromTitle.title || rawTitle || null;
    const titleStillLooksRawOrEmpty = !cleanFromTitle.title || (rawTitle && cleanFromTitle.title === rawTitle && cleanRawYouTubeTitleNoise(rawTitle) !== rawTitle);
    if (providedTrack && providedTrack.title) {
        title = providedTrack.title;
    } else if (ytmClean && ytmClean.title && ytmMeta?.album) {
        // YT Music Art Track panel gives exact canonical track title when album context is present
        title = ytmClean.title;
    } else if (externalMeta && externalMeta.title && titleStillLooksRawOrEmpty) {
        title = externalMeta.title;
    } else if (ytdlpTrackClean && (!title || titleStillLooksRawOrEmpty)) {
        title = ytdlpTrackClean;
    } else if (watchMeta && watchMeta.creditSong && (!title || title === rawTitle || isGenericUploaderChannel(rawChannel))) {
        title = cleanRawYouTubeTitleNoise(watchMeta.creditSong) || watchMeta.creditSong;
    } else if (ytmClean && ytmClean.title && (!title || title === rawTitle)) {
        title = ytmClean.title;
    }

    const collabs = [...cleanFromTitle.collaborators];
    const addCollab = (c) => {
        const cleanC = String(c || '').trim();
        if (!cleanC || isGenericUploaderChannel(cleanC)) return;
        if (!collabs.some(existing => normalizeLookupText(existing) === normalizeLookupText(cleanC))) {
            collabs.push(cleanC);
        }
    };

    let mainArtist = cleanFromTitle.mainArtist || null;
    const creditArtistParsed = watchMeta && watchMeta.creditArtist ? splitArtistCredits(watchMeta.creditArtist) : null;
    const ytmArtistClean = ytmMeta && ytmMeta.artist && !isGenericUploaderChannel(ytmMeta.artist)
        ? splitArtistCredits(ytmMeta.artist)
        : null;
    const extArtistClean = externalMeta && externalMeta.artist && !isGenericUploaderChannel(externalMeta.artist)
        ? splitArtistCredits(externalMeta.artist)
        : null;
    const ytdlpArtistClean = ytdlpMeta && ytdlpMeta.artist && !isGenericUploaderChannel(ytdlpMeta.artist)
        ? splitArtistCredits(ytdlpMeta.artist)
        : null;

    if (providedTrack && providedTrack.mainArtist) {
        mainArtist = providedTrack.mainArtist;
    } else if (!mainArtist || isGenericUploaderChannel(mainArtist) || !cleanFromTitle.artistFromTitle) {
        mainArtist =
            (ytmArtistClean && ytmArtistClean.mainArtist) ||
            (creditArtistParsed && creditArtistParsed.mainArtist) ||
            (extArtistClean && extArtistClean.mainArtist) ||
            (ytdlpArtistClean && ytdlpArtistClean.mainArtist) ||
            mainArtist ||
            null;
    } else if (isGenericUploaderChannel(mainArtist)) {
        mainArtist =
            (ytmArtistClean && ytmArtistClean.mainArtist) ||
            (creditArtistParsed && creditArtistParsed.mainArtist) ||
            (extArtistClean && extArtistClean.mainArtist) ||
            (ytdlpArtistClean && ytdlpArtistClean.mainArtist) ||
            null;
    }

    if (providedTrack) providedTrack.collaborators.forEach(addCollab);
    if (ytmMeta && Array.isArray(ytmMeta.collaborators)) ytmMeta.collaborators.forEach(addCollab);
    if (ytmArtistClean) ytmArtistClean.collaborators.forEach(addCollab);
    if (ytmClean) ytmClean.collaborators.forEach(addCollab);
    if (creditArtistParsed) creditArtistParsed.collaborators.forEach(addCollab);
    if (externalMeta && Array.isArray(externalMeta.collaborators)) externalMeta.collaborators.forEach(addCollab);
    if (extArtistClean) extArtistClean.collaborators.forEach(addCollab);
    if (ytdlpMeta && Array.isArray(ytdlpMeta.creators)) ytdlpMeta.creators.forEach(addCollab);
    if (ytdlpArtistClean) ytdlpArtistClean.collaborators.forEach(addCollab);

    // Dedupe collabs against chosen mainArtist
    const chosenArtistNorm = normalizeLookupText(mainArtist);
    const filteredCollabs = [];
    const seenCollabNorm = new Set(chosenArtistNorm ? [chosenArtistNorm] : []);
    for (const c of collabs) {
        const n = normalizeLookupText(c);
        if (!n || seenCollabNorm.has(n)) continue;
        seenCollabNorm.add(n);
        filteredCollabs.push(c);
    }

    const normalizedExtAlbum = externalMeta && externalMeta.albumTitle
        ? normalizeAlbumTitleAndType(externalMeta.albumTitle, externalMeta.albumType)
        : { albumTitle: null, albumType: null };

    let albumTitle =
        (providedTrack && providedTrack.albumTitle) ||
        (ytmMeta && ytmMeta.album) ||
        (watchMeta && watchMeta.creditAlbum) ||
        (ytdlpMeta && ytdlpMeta.album) ||
        descHints.albumTitle ||
        normalizedExtAlbum.albumTitle ||
        null;

    let albumType =
        (providedTrack && providedTrack.albumType) ||
        normalizedExtAlbum.albumType ||
        (externalMeta && externalMeta.albumType) ||
        descHints.albumType ||
        'album';

    if (albumTitle) {
        const normalizedMergedAlbum = normalizeAlbumTitleAndType(albumTitle, albumType);
        albumTitle = normalizedMergedAlbum.albumTitle;
        if (normalizedMergedAlbum.albumType) {
            albumType = normalizedMergedAlbum.albumType;
        }
    }

    let apiPublishYear = null;
    if (apiVideo && apiVideo.snippet && apiVideo.snippet.publishedAt) {
        const yrMatch = String(apiVideo.snippet.publishedAt).match(/^(\d{4})/);
        if (yrMatch) apiPublishYear = Number(yrMatch[1]);
    }

    const toValidYear = (val) => {
        const yr = Number(val);
        return Number.isInteger(yr) && yr >= 1900 && yr <= 2100 ? yr : null;
    };

    const authoritativeStudioYear =
        toValidYear(providedTrack && providedTrack.albumYear) ||
        toValidYear(externalMeta && externalMeta.releaseYear) ||
        toValidYear(ytmMeta && ytmMeta.year) ||
        toValidYear(descHints.albumYear) ||
        toValidYear(ytdlpMeta && ytdlpMeta.releaseYear);

    let albumYear =
        authoritativeStudioYear ||
        toValidYear(apiPublishYear) ||
        toValidYear(watchMeta && watchMeta.publishYear) ||
        toValidYear(ytdlpMeta && ytdlpMeta.uploadYear) ||
        null;

    let embeddable = null;
    if (apiVideo && apiVideo.status && typeof apiVideo.status.embeddable === 'boolean') {
        embeddable = apiVideo.status.embeddable;
    } else if (watchMeta && typeof watchMeta.embeddable === 'boolean') {
        embeddable = watchMeta.embeddable;
    }

    // Cross-reference the user's catalog:
    // 1. If the videoId is already saved for this user, reuse its curated metadata.
    const existingSong = videoId
        ? (catalogSongs || []).find(s => String(s.yt_video_id || '') === String(videoId))
        : null;
    if (existingSong) {
        metadataSources.push('catalog');
        if (existingSong.album_titulo && !albumTitle) {
            albumTitle = existingSong.album_titulo;
            if (existingSong.album_tipo && VALID_RELEASE_TYPES.has(existingSong.album_tipo)) {
                albumType = existingSong.album_tipo;
            }
        }
        const existingYear = toValidYear(existingSong.album_anio || existingSong.cancion_anio);
        if (existingYear && (!albumYear || !authoritativeStudioYear)) {
            albumYear = existingYear;
        }
    }

    // 2. Match detected albumTitle (or title-track matching same artist's album, e.g. DRIP -> Drip)
    const artistNorm = normalizeLookupText(mainArtist);
    const albumNorm = normalizeLookupText(albumTitle);
    const titleNorm = normalizeLookupText(title);
    let matchedAlbum = null;

    if (Array.isArray(catalogAlbums) && catalogAlbums.length) {
        if (albumNorm) {
            matchedAlbum = catalogAlbums.find(al => {
                const alNorm = normalizeLookupText(al.titulo);
                const alArtistNorm = normalizeLookupText(al.artista_principal_nombre || al.artista_nombre || '');
                return alNorm === albumNorm && (!artistNorm || !alArtistNorm || alArtistNorm === artistNorm);
            }) || catalogAlbums.find(al => normalizeLookupText(al.titulo) === albumNorm);
        } else if (titleNorm) {
            // Only match an unnamed album if its normalized title equals the song title for the same artist (title track).
            matchedAlbum = catalogAlbums.find(al => {
                const alNorm = normalizeLookupText(al.titulo);
                const alArtistNorm = normalizeLookupText(al.artista_principal_nombre || al.artista_nombre || '');
                return alNorm === titleNorm && (!artistNorm || !alArtistNorm || alArtistNorm === artistNorm);
            });
        }

        if (matchedAlbum) {
            if (!metadataSources.includes('catalog')) metadataSources.push('catalog');
            albumTitle = matchedAlbum.titulo;
            if (matchedAlbum.tipo_lanzamiento && VALID_RELEASE_TYPES.has(matchedAlbum.tipo_lanzamiento)) {
                albumType = matchedAlbum.tipo_lanzamiento;
            }
            const resolvedYear = toValidYear(matchedAlbum.anio || matchedAlbum.anio_lanzamiento);
            if (resolvedYear && (!albumYear || !authoritativeStudioYear)) {
                albumYear = resolvedYear;
            }
        }
    }

    if (filteredCollabs.length > 0 && albumType === 'single') {
        albumType = 'collab_single';
    }

    const finalAlbumNorm = normalizeLookupText(albumTitle);
    const suggestedAlbumIsSingleDuplicate = Boolean(
        !matchedAlbum &&
        !(existingSong && existingSong.album_titulo) &&
        albumTitle &&
        (albumType === 'single' || albumType === 'collab_single') &&
        titleNorm &&
        finalAlbumNorm === titleNorm
    );

    let suggestedArtistType = null;
    if (artistNorm && Array.isArray(catalogArtists) && catalogArtists.length) {
        const matchedArtist = catalogArtists.find(a =>
            normalizeLookupText(a.nombre || a.nombre_normalizado) === artistNorm
        );
        if (matchedArtist && ['solo', 'group', 'duo', 'collab_project'].includes(matchedArtist.tipo_artista)) {
            suggestedArtistType = matchedArtist.tipo_artista;
        }
    }

    const rawTrackNum = Number.parseInt(
        (ytdlpMeta && ytdlpMeta.trackNumber) ||
        (externalMeta && externalMeta.trackNumber) ||
        (existingSong && existingSong.numero_pista) ||
        '',
        10
    );
    const suggestedTrackNumber = Number.isInteger(rawTrackNum) && rawTrackNum >= 1 && rawTrackNum <= 999
        ? rawTrackNum
        : null;

    const suggestedLanguage = inferSuggestedSongLanguage({
        title: title || '',
        rawTitle,
        artist: mainArtist || '',
        description,
        genre: (externalMeta && externalMeta.genre) || ''
    });

    const apiPublishDate = (apiVideo?.snippet?.publishedAt && String(apiVideo.snippet.publishedAt).slice(0, 10)) || null;
    const suggestedReleaseDate =
        (providedTrack && providedTrack.releaseDate) ||
        (externalMeta && externalMeta.releaseDate) ||
        (watchMeta && watchMeta.publishDate) ||
        apiPublishDate ||
        null;

    return {
        suggestedTitle: title ? String(title).slice(0, 180) : null,
        suggestedArtist: mainArtist ? String(mainArtist).slice(0, 140) : null,
        suggestedCollaborators: filteredCollabs.join(', ').slice(0, 300),
        suggestedAlbumTitle: albumTitle ? String(albumTitle).slice(0, 180) : null,
        suggestedAlbumType: VALID_RELEASE_TYPES.has(albumType) ? albumType : 'album',
        suggestedAlbumYear: Number.isInteger(albumYear) && albumYear >= 1900 && albumYear <= 2100 ? albumYear : null,
        suggestedReleaseDate,
        suggestedLanguage,
        suggestedArtistType,
        suggestedTrackNumber,
        suggestedAlbumIsSingleDuplicate,
        metadataSources,
        embeddable
    };
}

function _parseSubtitleTimeSeconds(rawTs) {
    const clean = String(rawTs || '').trim().replace(',', '.');
    const parts = clean.split(':');
    if (parts.length === 2) {
        return (Number.parseFloat(parts[0]) || 0) * 60 + (Number.parseFloat(parts[1]) || 0);
    }
    if (parts.length === 3) {
        return (Number.parseFloat(parts[0]) || 0) * 3600 + (Number.parseFloat(parts[1]) || 0) * 60 + (Number.parseFloat(parts[2]) || 0);
    }
    return null;
}

