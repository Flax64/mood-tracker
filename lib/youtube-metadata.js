/**
 * Segment unformatted or continuous long lyric blocks (>= 8 lines without blank lines)
 * into readable stanzas regardless of script (Latin, Hangul, Kana/Kanji) or punctuation.
 * @param {string} text
 * @param {number} [maxLinesPerStanza=4]
 * @returns {string}
 */
function segmentLyricsIntoStanzas(text, maxLinesPerStanza = 4) {
    const raw = String(text || '').replace(/\r\n?/g, '\n').trim();
    if (!raw) return '';
    const lines = raw.split('\n').map((ln) => ln.trimEnd());
    const existingBreaks = lines.filter((ln) => !ln.trim()).length;
    const blockLimit = existingBreaks >= 3 ? Math.max(maxLinesPerStanza * 2 + 2, 10) : maxLinesPerStanza * 2;
    const out = [];
    let block = [];

    const flushBlock = (blk) => {
        const nonEmpty = blk.filter((l) => l.trim());
        if (!nonEmpty.length) return;
        if (nonEmpty.length < blockLimit) {
            out.push(...nonEmpty);
            return;
        }
        for (let i = 0; i < nonEmpty.length; i += maxLinesPerStanza) {
            if (i > 0) out.push('');
            out.push(...nonEmpty.slice(i, i + maxLinesPerStanza));
        }
    };

    for (const ln of lines) {
        const s = ln.trim();
        if (!s) {
            if (block.length) {
                flushBlock(block);
                block = [];
            }
            if (out.length && out[out.length - 1] !== '') out.push('');
            continue;
        }
        if (STRUCTURAL_LYRIC_TAG_RE.test(s) || /^===\s*\[[^\]]+\]\s*===$/.test(s)) {
            if (block.length) {
                flushBlock(block);
                block = [];
            }
            if (out.length && out[out.length - 1] !== '') out.push('');
            out.push(s);
            continue;
        }
        block.push(ln);
    }
    if (block.length) flushBlock(block);
    return out.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

/**
 * Convert `.srt`, `.vtt`, `.lrc`, or timestamped caption text into clean readable lyric lines
 * while stripping timestamps, cue indices, VTT headers, inline `<c>` tags, and rolling duplicates,
 * and preserving musical pauses (>= 2.5s gap) as stanza breaks.
 * @param {string} rawText
 * @returns {string}
 */
function cleanCaptionTextToLyrics(rawText) {
    const normalized = String(rawText || '')
        .replace(/[\uFEFF\u200B-\u200D\u2060]/g, '')
        .replace(/\r\n?/g, '\n')
        .replace(/<br\s*\/?>/gi, '\n')
        .replace(/\\N/g, '\n');
    if (!normalized.trim()) return '';

    const rawLines = normalized.split('\n');
    const resultLines = [];
    let skippingVttBlock = false;
    let prevCueEndSec = null;
    let prevLrcSec = null;
    let pendingStanzaBreak = false;

    for (const rawLine of rawLines) {
        let line = rawLine.trim();

        if (!line) {
            skippingVttBlock = false;
            continue;
        }
        if (/^(?:WEBVTT(?:\s|$)|Kind:|Language:)/i.test(line)) {
            continue;
        }
        if (/^(?:NOTE|STYLE|REGION)(?:\s|$)/.test(line)) {
            skippingVttBlock = true;
            continue;
        }
        if (skippingVttBlock) continue;

        // SRT sequence index or VTT timestamp lines
        if (/^\d+$/.test(line)) continue;
        const cueMatch = line.match(/^((?:\d{1,2}:)?\d{2}:\d{2}[.,]\d{2,3})\s*-->\s*((?:\d{1,2}:)?\d{2}:\d{2}[.,]\d{2,3})/);
        if (cueMatch) {
            const cueStart = _parseSubtitleTimeSeconds(cueMatch[1]);
            const cueEnd = _parseSubtitleTimeSeconds(cueMatch[2]);
            if (prevCueEndSec !== null && cueStart !== null && (cueStart - prevCueEndSec) >= 2.5) {
                pendingStanzaBreak = true;
            }
            if (cueEnd !== null) prevCueEndSec = cueEnd;
            continue;
        }

        // LRC metadata tags like [ar:...], [ti:...], [al:...], [by:...]
        if (/^\[(?:ar|ti|al|au|by|offset|re|ve|length)\s*:[^\]]*\]$/i.test(line)) {
            continue;
        }

        // Check leading LRC timestamp gap (>= 2.5s pause between sung lines)
        const lrcLead = line.match(/^\[(\d{1,2}):(\d{2})(?:[.:](\d{1,3}))?\]/);
        if (lrcLead) {
            const frac = lrcLead[3] ? Number(`0.${lrcLead[3].padEnd(3, '0').slice(0, 3)}`) : 0;
            const lrcSec = (Number.parseInt(lrcLead[1], 10) || 0) * 60 + (Number.parseInt(lrcLead[2], 10) || 0) + frac;
            if (prevLrcSec !== null && (lrcSec - prevLrcSec) >= 3.8) {
                pendingStanzaBreak = true;
            }
            prevLrcSec = lrcSec;
        }

        // Strip LRC inline timestamps `[01:23.45]` and YouTube `<00:01:23.456>` / `<c>` / `<i>` tags
        line = line
            .replace(/\[\d{1,2}:\d{2}(?:[.:]\d{1,3})?\]/g, '')
            .replace(/<\d{1,2}:\d{2}:\d{2}(?:[.,]\d{1,3})?>/g, '')
            .replace(/<\/?[^>]+>/g, '')
            .replace(/\s+/g, ' ')
            .trim();

        line = decodeHtmlEntities(line);
        if (!line) continue;

        if (STRUCTURAL_LYRIC_TAG_RE.test(line)) {
            pendingStanzaBreak = true;
        }

        // Avoid repeating identical consecutive lines caused by YouTube rolling auto-captions
        const lastNonEmpty = [...resultLines].reverse().find((l) => l !== '');
        if (lastNonEmpty === line) {
            continue;
        }
        if (pendingStanzaBreak && resultLines.length > 0 && resultLines[resultLines.length - 1] !== '') {
            resultLines.push('');
        }
        pendingStanzaBreak = false;
        resultLines.push(line);
    }

    return segmentLyricsIntoStanzas(resultLines.join('\n').trim());
}

